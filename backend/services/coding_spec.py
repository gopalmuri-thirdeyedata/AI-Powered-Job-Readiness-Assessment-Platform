# The hidden program: prelude + the student's code + the driver
# ------------------------------------------------------------------------------
def _driver_python(spec: Dict[str, Any], marker: str) -> str:
    reads = "\n".join(f"    a{i} = _pw_read('{p['type']}')" for i, p in enumerate(spec["params"]))
    call_args = ", ".join(f"a{i}" for i in range(len(spec["params"])))
    return f'''import sys as _pw_sys, json as _pw_json
_pw_sys.setrecursionlimit(6000)

def _pw_main():
    _lines = _pw_sys.stdin.read().split("\\n")
    _pos = [0]

    def _line():
        value = _lines[_pos[0]] if _pos[0] < len(_lines) else ""
        _pos[0] += 1
        return value

    def _pw_read(t):
        if t in ("int", "long"):
            return int(_line())
        if t == "double":
            return float(_line())
        if t == "bool":
            return _line().strip() == "1"
        if t == "string":
            return _line()
        if t == "string[]":
            return [_line() for _ in range(int(_line()))]
        if t == "int[][]":
            return [[int(x) for x in _line().split()][1:] for _ in range(int(_line()))]
        n = int(_line())
        kind = {{"int[]": int, "long[]": int, "double[]": float, "bool[]": lambda x: x == "1"}}[t]
        return [kind(x) for x in _line().split()[:n]]

{reads}
    _result = Solution().{spec['name']}({call_args})
    _pw_sys.stdout.write("\\n{marker}" + _pw_json.dumps(_result) + "\\n")
    _pw_sys.stdout.flush()


_pw_main()
'''


