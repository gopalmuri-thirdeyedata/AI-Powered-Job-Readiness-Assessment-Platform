"""
Language-neutral coding problems (Python, Java, C++ and C) in the LeetCode style.

A problem is described ONCE by a typed signature, for example
    {"name": "twoSum", "params": [{"name": "nums", "type": "int[]"}, {"name": "target", "type": "int"}], "returns": "int[]"}
and everything else is generated by this module, deterministically, never by the AI:

  * `starter_code()`  what the student sees: only the class / function signature with an empty body, as on LeetCode;
  * `compose()`       the program the sandbox runs: hidden imports + the student's code + a hidden `main` that reads one test from
                      stdin, calls the student's function and prints the result as one JSON line behind a random marker;
  * `encode_input()`  the stdin of one test. ONE format for every language: one value per line (see _encode); the same bytes feed
                      the Python, Java, C++ and C drivers, so a test case never depends on the language;
  * `parse_result()` / `compare_values()`  the server reads the marked JSON line and compares it with the expected value
                      (exact, any order, or with a tolerance for decimals). Expected values never reach the sandbox.

Supported types (kept small on purpose so all four languages can express them): int, long, double, bool, string, int[], long[],
double[], bool[], string[], int[][]. Strings are printable ASCII on one line. No linked lists or trees.
"""
import json
import math
import re
import secrets
from typing import Any, Dict, List, Optional, Tuple

LANGUAGES = ("python", "java", "cpp", "c")
LANGUAGE_LABELS = {"python": "Python3", "java": "Java", "cpp": "C++", "c": "C"}
_LANGUAGE_ALIASES = {"python": "python", "python3": "python", "py": "python", "java": "java", "cpp": "cpp", "c++": "cpp",
                     "cplusplus": "cpp", "c": "c"}

TYPES = ("int", "long", "double", "bool", "string", "int[]", "long[]", "double[]", "bool[]", "string[]", "int[][]")
COMPARE_MODES = ("exact", "unordered", "unordered_nested")
MAX_PARAMS = 6
MAX_ENCODED_BYTES = 60 * 1024            # the sandbox accepts 64 KB of stdin
MAX_STRING_CHARS = 5000
DOUBLE_TOLERANCE = 1e-6

_INT_RANGE = {"int": (-2 ** 31, 2 ** 31 - 1), "long": (-2 ** 63, 2 ** 63 - 1)}

