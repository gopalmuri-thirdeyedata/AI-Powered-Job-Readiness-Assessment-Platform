# Reading the program's answer and comparing
# ------------------------------------------------------------------------------
def new_marker() -> str:
    return "@@PW" + secrets.token_hex(8) + "@@"


def parse_result(stdout: str, marker: str) -> Tuple[bool, Any, str]:
    """(found, value, the student's own prints). The answer is the LAST line that starts with the marker."""
    lines = str(stdout or "").replace("\r\n", "\n").split("\n")
    for index in range(len(lines) - 1, -1, -1):
        if lines[index].startswith(marker):
            try:
                value = json.loads(lines[index][len(marker):])
            except ValueError:
                return False, None, "\n".join(lines[:index]).strip()
            return True, value, "\n".join(lines[:index] + lines[index + 1:]).strip()
    return False, None, str(stdout or "").strip()


def _sort_key(value: Any) -> str:
    return json.dumps(value, sort_keys=True, separators=(",", ":"))


def _equal(actual: Any, expected: Any, vtype: str) -> bool:
    if vtype.endswith("[]"):
        if not isinstance(actual, list) or not isinstance(expected, list) or len(actual) != len(expected):
            return False
        inner = vtype[:-2]
        return all(_equal(a, e, inner) for a, e in zip(actual, expected))
    if vtype == "double":
        if isinstance(actual, bool) or not isinstance(actual, (int, float)):
            return False
        return abs(float(actual) - float(expected)) <= DOUBLE_TOLERANCE * max(1.0, abs(float(expected)))
    if vtype == "bool":
        return isinstance(actual, bool) and actual == expected
    if vtype in ("int", "long"):
        if isinstance(actual, bool) or not isinstance(actual, (int, float)) or (isinstance(actual, float) and not actual.is_integer()):
            return False
        return int(actual) == int(expected)
    return isinstance(actual, str) and actual == expected


def compare_values(spec: Dict[str, Any], actual: Any, expected: Any) -> bool:
    """Does the student's returned value equal the expected one? Decimals use a tolerance; list order can be ignored per problem."""
    vtype, mode = spec["returns"], spec.get("compare", "exact")
    if mode != "exact" and isinstance(actual, list) and isinstance(expected, list):
        if mode == "unordered_nested":
            actual = [sorted(r, key=_sort_key) if isinstance(r, list) else r for r in actual]
            expected = [sorted(r, key=_sort_key) if isinstance(r, list) else r for r in expected]
        actual, expected = sorted(actual, key=_sort_key), sorted(expected, key=_sort_key)
    return _equal(actual, expected, vtype)


