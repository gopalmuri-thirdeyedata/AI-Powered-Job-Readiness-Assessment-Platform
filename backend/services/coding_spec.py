def compose(spec: Dict[str, Any], language: str, student_code: str, marker: str) -> Tuple[str, int]:
    """
    The program for the sandbox and the number of hidden lines BEFORE the student's first line (error line numbers are shifted back
    by it so they match the editor). Python: one hidden import line. Java: the imports share the student's first line, so no shift.
    C / C++: a `#line 1` directive restarts the numbering at the student's code.
    """
    language = normalize_language(language)
    code = (student_code or "").rstrip()
    driver = _DRIVERS[language](spec, marker)
    if language == "python":
        from services import function_style
        return f"{function_style.STANDARD_IMPORTS}\n{code}\n\n\n{driver}", 1
    if language == "java":
        code = _JAVA_PUBLIC_SOLUTION.sub(r"\1", code)       # `public class Solution` would have to live in Solution.java
        return "import java.util.*; " + code + "\n\n" + driver, 0
    prelude = _CPP_PRELUDE if language == "cpp" else _C_PRELUDE
    return f"{prelude}{code}\n\n{driver}", 0


_JAVA_ERR_LINE = re.compile(r"(Main\.java):(\d+)")
_PY_LINE = re.compile(r"(\bline )(\d+)")
_C_ERR_LINE = re.compile(r"main\.(?:cpp|c):(\d+)")


def fix_error_lines(language: str, text: Optional[str], shift: int) -> Optional[str]:
    """Error text in terms of the student's editor: remove the hidden prelude line(s) from Python tracebacks."""
    if not text or not shift or normalize_language(language) != "python":
        return text
    return _PY_LINE.sub(lambda m: f"{m.group(1)}{int(m.group(2)) - shift}" if int(m.group(2)) > shift else m.group(0), str(text))


def friendly_compile_error(language: str, text: Optional[str], student_code: str, spec: Dict[str, Any]) -> Optional[str]:
    """Compiler output, plus a hint when the error is in the hidden driver (it means the function signature was changed)."""
    if not text or normalize_language(language) in ("python",):
        return text
    lines = (student_code or "").count("\n") + 1
    for match in list(_JAVA_ERR_LINE.finditer(text)) + list(_C_ERR_LINE.finditer(text)):
        number = int(match.group(2) if match.re is _JAVA_ERR_LINE else match.group(1))
        if number > lines:
            params = ", ".join(f"{p['name']}: {p['type']}" for p in spec["params"])
            return (f"{text.strip()}\n\nHint: this error is outside your code. Keep the function `{spec['name']}` and its parameters "
                    f"({params}) exactly as in the starter code.")
    return text


def stub_solution(spec: Dict[str, Any], language: str) -> str:
    """A body that compiles and returns an empty value (used to check that a starter + driver pair builds)."""
    language = normalize_language(language)
    starter = starter_code(spec, language)
    ret = spec["returns"]
    if language == "python":
        return starter.replace("        pass", "        return None")
    if language == "java":
        default = {"int": "0", "long": "0L", "double": "0.0", "bool": "false", "string": '""', "int[]": "new int[0]", "long[]": "new long[0]",
                   "double[]": "new double[0]", "bool[]": "new boolean[0]", "string[]": "new String[0]", "int[][]": "new int[0][]"}[ret]
        return starter.replace("        \n", f"        return {default};\n", 1)
    if language == "cpp":
        return starter.replace("        \n", "        return {};\n", 1)
    if ret in _C_SCALARS:
        body = '    return "";\n' if ret == "string" else "    return 0;\n"
    else:
        body = "    *returnSize = 0;\n" + ("    *returnColumnSizes = NULL;\n" if ret == "int[][]" else "") + "    return NULL;\n"
    return starter.replace("    \n}", body + "}", 1)
