_IDENT = re.compile(r"^[A-Za-z][A-Za-z0-9]{0,39}$")

_PY_TYPES = {"int": "int", "long": "int", "double": "float", "bool": "bool", "string": "str", "int[]": "List[int]", "long[]": "List[int]",
             "double[]": "List[float]", "bool[]": "List[bool]", "string[]": "List[str]", "int[][]": "List[List[int]]"}
_JAVA_TYPES = {"int": "int", "long": "long", "double": "double", "bool": "boolean", "string": "String", "int[]": "int[]", "long[]": "long[]",
               "double[]": "double[]", "bool[]": "boolean[]", "string[]": "String[]", "int[][]": "int[][]"}
_CPP_TYPES = {"int": "int", "long": "long long", "double": "double", "bool": "bool", "string": "string", "int[]": "vector<int>",
              "long[]": "vector<long long>", "double[]": "vector<double>", "bool[]": "vector<bool>", "string[]": "vector<string>",
              "int[][]": "vector<vector<int>>"}
# C: element type of an array; scalars map to themselves
_C_SCALARS = {"int": "int", "long": "long long", "double": "double", "bool": "bool", "string": "char*"}
_C_ELEMENT = {"int[]": "int", "long[]": "long long", "double[]": "double", "bool[]": "bool", "string[]": "char*"}
# short codes used in the helper names of the generated programs
_CODE = {"int": "i", "long": "l", "double": "d", "bool": "b", "string": "s", "int[]": "ia", "long[]": "la", "double[]": "da",
         "bool[]": "ba", "string[]": "sa", "int[][]": "ii"}


def normalize_language(language: Optional[str]) -> str:
    key = _LANGUAGE_ALIASES.get((language or "python").strip().lower())
    if key is None:
        raise ValueError("Supported languages: Python, Java, C++ and C.")
    return key


# ------------------------------------------------------------------------------
# The signature
# ------------------------------------------------------------------------------
def _check_name(name: Any, what: str) -> str:
    text = str(name or "").strip()
    if not _IDENT.match(text):
        raise ValueError(f"{what} '{text}' must be letters and digits only, starting with a letter (max 40 characters).")
    if text in _RESERVED:
        raise ValueError(f"{what} '{text}' is a reserved word in one of the supported languages.")
    return text


def validate_spec(raw: Any) -> Dict[str, Any]:
    """The normalized spec {"name", "params": [{"name", "type"}], "returns", "compare"}; ValueError (readable) when unusable."""
    if not isinstance(raw, dict):
        raise ValueError("signature is missing")
    name = _check_name(raw.get("name") or raw.get("function"), "Function name")
    params_in = raw.get("params")
    if not isinstance(params_in, list) or not (1 <= len(params_in) <= MAX_PARAMS):
        raise ValueError(f"a signature needs 1 to {MAX_PARAMS} parameters")
    params, seen = [], {name.lower()}
    for item in params_in:
        if not isinstance(item, dict):
            raise ValueError("every parameter needs a name and a type")
        pname = _check_name(item.get("name"), "Parameter name")
        ptype = str(item.get("type") or "").strip()
        if ptype not in TYPES:
            raise ValueError(f"parameter '{pname}' has unsupported type '{ptype}' (use one of: {', '.join(TYPES)})")
        if pname.lower() in seen:
            raise ValueError(f"'{pname}' is used twice")
        seen.add(pname.lower())
        params.append({"name": pname, "type": ptype})
    returns = str(raw.get("returns") or raw.get("return_type") or "").strip()
    if returns not in TYPES:
        raise ValueError(f"unsupported return type '{returns}' (use one of: {', '.join(TYPES)})")
    compare = str(raw.get("compare") or "exact").strip()
    if compare not in COMPARE_MODES:
        compare = "exact"
    if compare != "exact" and not returns.endswith("[]"):
        compare = "exact"
    if compare == "unordered_nested" and returns != "int[][]":
        compare = "unordered"
    return {"name": name, "params": params, "returns": returns, "compare": compare}


