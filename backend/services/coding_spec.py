def _starter_python(spec: Dict[str, Any]) -> str:
    args = "".join(f", {p['name']}: {_PY_TYPES[p['type']]}" for p in spec["params"])
    return f"class Solution:\n    def {spec['name']}(self{args}) -> {_PY_TYPES[spec['returns']]}:\n        pass\n"


def _starter_java(spec: Dict[str, Any]) -> str:
    args = ", ".join(f"{_JAVA_TYPES[p['type']]} {p['name']}" for p in spec["params"])
    return f"class Solution {{\n    public {_JAVA_TYPES[spec['returns']]} {spec['name']}({args}) {{\n        \n    }}\n}}\n"


def _starter_cpp(spec: Dict[str, Any]) -> str:
    def param(p):
        ctype = _CPP_TYPES[p["type"]]
        return f"{ctype}& {p['name']}" if p["type"].endswith("[]") else f"{ctype} {p['name']}"
    args = ", ".join(param(p) for p in spec["params"])
    return f"class Solution {{\npublic:\n    {_CPP_TYPES[spec['returns']]} {spec['name']}({args}) {{\n        \n    }}\n}};\n"


def _c_param_list(spec: Dict[str, Any]) -> List[str]:
    out: List[str] = []
    for p in spec["params"]:
        t, n = p["type"], p["name"]
        if t in _C_SCALARS:
            out.append(f"{_C_SCALARS[t]} {n}")
        elif t == "int[][]":
            out += [f"int** {n}", f"int {n}Size", f"int* {n}ColSize"]
        else:
            out += [f"{_C_ELEMENT[t]}* {n}", f"int {n}Size"]
    return out


def _starter_c(spec: Dict[str, Any]) -> str:
    ret = spec["returns"]
    params = _c_param_list(spec)
    if ret in _C_SCALARS:
        rtype = _C_SCALARS[ret]
        note = " * Note: The returned string must be malloced, assume caller calls free().\n" if ret == "string" else ""
    elif ret == "int[][]":
        rtype = "int**"
        params += ["int* returnSize", "int** returnColumnSizes"]
        note = (" * Note: The returned array must be malloced, assume caller calls free().\n"
                " * Return the number of rows in *returnSize and the length of each row in (*returnColumnSizes)[i].\n")
    else:
        rtype = _C_ELEMENT[ret] + "*"
        params += ["int* returnSize"]
        note = " * Note: The returned array must be malloced, assume caller calls free().\n * Set *returnSize to the length of the returned array.\n"
    header = f"/**\n{note} */\n" if note else ""
    return f"{header}{rtype} {spec['name']}({', '.join(params)}) {{\n    \n}}\n"


_STARTERS = {"python": _starter_python, "java": _starter_java, "cpp": _starter_cpp, "c": _starter_c}


def starter_code(spec: Dict[str, Any], language: str) -> str:
    return _STARTERS[normalize_language(language)](spec)


def all_starters(spec: Dict[str, Any]) -> Dict[str, str]:
    return {lang: _STARTERS[lang](spec) for lang in LANGUAGES}


