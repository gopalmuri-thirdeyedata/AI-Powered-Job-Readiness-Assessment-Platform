# Values: validation, the stdin format, display text
# ------------------------------------------------------------------------------
def _scalar(value: Any, vtype: str, where: str) -> Any:
    if vtype in ("int", "long"):
        if isinstance(value, bool) or not isinstance(value, (int, float)) or (isinstance(value, float) and not value.is_integer()):
            raise ValueError(f"{where}: expected an integer")
        number = int(value)
        low, high = _INT_RANGE[vtype]
        if not low <= number <= high:
            raise ValueError(f"{where}: {number} is out of the {vtype} range")
        return number
    if vtype == "double":
        if isinstance(value, bool) or not isinstance(value, (int, float)) or not math.isfinite(float(value)):
            raise ValueError(f"{where}: expected a number")
        return float(value)
    if vtype == "bool":
        if not isinstance(value, bool):
            raise ValueError(f"{where}: expected true or false")
        return value
    if vtype == "string":
        if not isinstance(value, str):
            raise ValueError(f"{where}: expected a string in double quotes")
        if len(value) > MAX_STRING_CHARS or any(not (32 <= ord(ch) <= 126) for ch in value):
            raise ValueError(f"{where}: a string may only hold printable ASCII characters on one line (max {MAX_STRING_CHARS})")
        return value
    raise ValueError(f"{where}: unsupported type {vtype}")


def check_value(value: Any, vtype: str, where: str = "value") -> Any:
    """The value coerced to its type (an int given as 3.0 becomes 3); ValueError with a readable message otherwise."""
    if vtype.endswith("[][]"):
        if not isinstance(value, list):
            raise ValueError(f"{where}: expected an array of arrays")
        return [check_value(row, vtype[:-2], f"{where}[{i}]") for i, row in enumerate(value)]
    if vtype.endswith("[]"):
        if not isinstance(value, list):
            raise ValueError(f"{where}: expected an array")
        return [_scalar(item, vtype[:-2], f"{where}[{i}]") for i, item in enumerate(value)]
    return _scalar(value, vtype, where)


def check_args(spec: Dict[str, Any], values: Any) -> List[Any]:
    if not isinstance(values, list) or len(values) != len(spec["params"]):
        raise ValueError(f"expected {len(spec['params'])} input value(s), one per parameter")
    return [check_value(v, p["type"], p["name"]) for v, p in zip(values, spec["params"])]


def _flat(value: Any, vtype: str) -> List[str]:
    """The lines of one value: scalar = 1 line; T[] = count line + values line; string[] = count + one line each; int[][] = rows + one line per row."""
    if vtype == "bool":
        return ["1" if value else "0"]
    if vtype == "double":
        return [repr(float(value))]
    if vtype in ("int", "long"):
        return [str(int(value))]
    if vtype == "string":
        return [value]
    if vtype == "string[]":
        return [str(len(value))] + list(value)
    if vtype == "int[][]":
        return [str(len(value))] + [" ".join([str(len(row))] + [str(x) for x in row]) for row in value]
    element = vtype[:-2]
    return [str(len(value)), " ".join(_flat(x, element)[0] for x in value)]


def encode_input(spec: Dict[str, Any], values: List[Any]) -> str:
    """The stdin of one test (validated first). Raises ValueError when a value does not fit its parameter type."""
    values = check_args(spec, values)
    lines: List[str] = []
    for value, param in zip(values, spec["params"]):
        lines.extend(_flat(value, param["type"]))
    text = "\n".join(lines) + "\n"
    if len(text.encode("utf-8")) > MAX_ENCODED_BYTES:
        raise ValueError("the test input is too large")
    return text


def _compact(value: Any) -> str:
    return json.dumps(value, separators=(",", ":"), ensure_ascii=True)


def display_values(spec: Dict[str, Any], values: List[Any]) -> List[str]:
    return [_compact(v) for v in values]


def display_input(spec: Dict[str, Any], values: List[Any]) -> str:
    """LeetCode's way of showing an input: `nums = [2,7,11,15]` / `target = 9`, one parameter per line."""
    return "\n".join(f"{p['name']} = {_compact(v)}" for p, v in zip(spec["params"], values))


def parse_custom_input(spec: Dict[str, Any], text: str) -> List[Any]:
    """The student's own testcase: one JSON value per line, one line per parameter, in order. ValueError tells them what is wrong."""
    lines = [ln for ln in str(text or "").replace("\r\n", "\n").split("\n") if ln.strip() != ""]
    params = spec["params"]
    if len(lines) != len(params):
        raise ValueError(f"Your testcase needs {len(params)} line(s), one value per parameter ({', '.join(p['name'] for p in params)}); it has {len(lines)}.")
    values = []
    for line, param in zip(lines, params):
        try:
            parsed = json.loads(line)
        except ValueError:
            raise ValueError(f"{param['name']}: '{line.strip()[:60]}' is not valid. Use JSON, for example [1,2,3], 42, true or \"text\".")
        values.append(check_value(parsed, param["type"], param["name"]))
    return values


