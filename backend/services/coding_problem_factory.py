def sandbox_run_batch(language: str, program: str, stdins: List[str]) -> Dict[str, Any]:
    """The code sandbox (in-house runner, Judge0 as the fallback), waiting out a busy runner. Raises SandboxUnavailable when it is down."""
    from services import assessment_engine as engine, judge0_service
    return engine.run_batch_with_retry(judge0_service.execute_batch, language, program, stdins)


def local_run_batch(language: str, program: str, stdins: List[str]) -> Dict[str, Any]:
    """
    Offline fixtures only (GEMINI_MOCK_MODE): the mock problems are trusted code written in this repository, so they run in a plain local
    Python subprocess and development/tests need no sandbox. Never used for anything an AI or a student wrote.
    """
    results = []
    for stdin in stdins:
        proc = subprocess.run([sys.executable, "-I", "-c", program], input=stdin, capture_output=True, text=True, timeout=20)
        results.append({"status": "success" if proc.returncode == 0 else "failed", "stdout": proc.stdout, "stderr": proc.stderr,
                        "output": proc.stderr or proc.stdout, "compile_output": "", "timed_out": False, "execution_time_ms": None, "raw": {}})
    return {"status": "success", "output": "", "compile_output": "", "results": results}
