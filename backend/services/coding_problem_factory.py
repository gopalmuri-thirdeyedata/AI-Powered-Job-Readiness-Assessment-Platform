"""
Turns what Gemini wrote for ONE coding problem into a verified, language-neutral blueprint problem.

Gemini gives: a typed signature, 2 examples, a pool of hidden-test candidates and a reference solution (Python). Gemini's own "expected"
values are never trusted on their own: the reference solution is RUN (in the code sandbox) on every input, and a test is kept only when
the reference and Gemini agree. So a wrong answer key (or an unsolvable problem) is caught here, at generation time, instead of
unfairly failing every student later. The stored problem has exactly 2 public examples and 5 hidden tests, the signature, and starter code
for Python, Java, C++ and C generated by services.coding_spec.
"""
import json
import subprocess
import sys
from typing import Any, Callable, Dict, List, Optional

from services import coding_spec

EXAMPLE_COUNT = 2
HIDDEN_COUNT = 5
MAX_HIDDEN_CANDIDATES = 8
MAX_CONSTRAINTS = 8
MAX_TEXT_CHARS = 4000
MAX_REFERENCE_CHARS = 12000

RunBatch = Callable[[str, str, List[str]], Dict[str, Any]]


class ProblemRejected(Exception):
    """The generated problem cannot be published as it is; the message says why (it is fed back to Gemini on the retry)."""


def _reject(message: str):
    raise ProblemRejected(message)


def _values_of(spec: Dict[str, Any], data: Any, where: str) -> List[Any]:
    names = [p["name"] for p in spec["params"]]
    if isinstance(data, dict):
        missing = [n for n in names if n not in data]
        if missing:
            raise ValueError(f"{where}: missing input value(s) {', '.join(missing)}")
        values = [data[n] for n in names]
    elif isinstance(data, list):
        values = data
    else:
        raise ValueError(f"{where}: input must be an object keyed by parameter name")
    return coding_spec.check_args(spec, values)


def _case(spec: Dict[str, Any], raw: Any, where: str) -> Dict[str, Any]:
    if not isinstance(raw, dict) or "expected" not in raw:
        raise ValueError(f"{where}: needs 'input' and 'expected'")
    values = _values_of(spec, raw.get("input"), where)
    expected = coding_spec.check_value(raw["expected"], spec["returns"], f"{where} expected")
    return {"values": values, "expected": expected, "stdin": coding_spec.encode_input(spec, values),
            "explanation": str(raw.get("explanation") or "").strip()[:MAX_TEXT_CHARS]}


def _named(spec: Dict[str, Any], values: List[Any]) -> Dict[str, Any]:
    return {p["name"]: v for p, v in zip(spec["params"], values)}


def build_problem(raw: Any, problem_id: str, run_batch: RunBatch) -> Dict[str, Any]:
    """
    Verify and normalize one generated problem. `run_batch(language, program, stdins)` runs a program once per stdin (the sandbox) and
    may raise SandboxUnavailable (not swallowed here). Raises ProblemRejected with a readable reason when the problem is not usable.
    """
    if not isinstance(raw, dict):
        _reject("the coding problem must be a JSON object")
    try:
        spec = coding_spec.validate_spec({**(raw.get("signature") or {}), "compare": raw.get("compare")})
    except ValueError as exc:
        _reject(f"invalid signature: {exc}")
    title = str(raw.get("title") or "").strip()[:200]
    description = str(raw.get("description") or "").strip()[:MAX_TEXT_CHARS]
    if not title or len(description) < 20:
        _reject("the problem needs a title and a description")
    difficulty = str(raw.get("difficulty") or "Medium").strip().title()
    if difficulty not in ("Easy", "Medium", "Hard"):
        difficulty = "Medium"
    constraints = [str(c).strip() for c in (raw.get("constraints") or []) if str(c).strip()][:MAX_CONSTRAINTS] if isinstance(raw.get("constraints"), list) else []
    reference = raw.get("reference_solution")
    if not isinstance(reference, str) or len(reference) > MAX_REFERENCE_CHARS or "class Solution" not in reference or f"def {spec['name']}" not in reference:
        _reject(f"reference_solution must be a Python `class Solution` with a method named {spec['name']}")

    examples_in = raw.get("examples")
    if not isinstance(examples_in, list) or len(examples_in) < EXAMPLE_COUNT:
        _reject(f"exactly {EXAMPLE_COUNT} examples are required")
    examples: List[Dict[str, Any]] = []
    for i, item in enumerate(examples_in[:EXAMPLE_COUNT]):
        try:
            examples.append(_case(spec, item, f"example {i + 1}"))
        except ValueError as exc:
            _reject(f"example {i + 1} is invalid: {exc}")
    hidden_in = raw.get("hidden_tests") if isinstance(raw.get("hidden_tests"), list) else raw.get("hidden_test_cases")
    if not isinstance(hidden_in, list):
        _reject("hidden_tests must be a list")
    seen = {e["stdin"] for e in examples}
    hidden: List[Dict[str, Any]] = []
    for i, item in enumerate(hidden_in):
        try:
            case = _case(spec, item, f"hidden test {i + 1}")
        except ValueError:
            continue                                 # an unusable candidate is dropped; only the final count matters
        if case["stdin"] not in seen:
            seen.add(case["stdin"])
            hidden.append(case)
        if len(hidden) >= MAX_HIDDEN_CANDIDATES:
            break
    if len(hidden) < HIDDEN_COUNT:
        _reject(f"only {len(hidden)} valid distinct hidden tests; {HIDDEN_COUNT} are required (each input must match the declared types)")

    # Run the reference solution on every input: it, not Gemini's typing, decides what the answers are
    marker = coding_spec.new_marker()
    program, _ = coding_spec.compose(spec, "python", reference, marker)
    cases = examples + hidden
    result = run_batch("python", program, [c["stdin"] for c in cases])
    if result.get("status") == "error":
        _reject("the reference solution does not compile: " + str(result.get("compile_output") or result.get("output") or "")[:300])
    outputs = result.get("results") or []
    if len(outputs) != len(cases):
        _reject("the reference solution could not be run on every test")
    agreed: List[Dict[str, Any]] = []
    for index, (case, one) in enumerate(zip(cases, outputs)):
        label = f"example {index + 1}" if index < EXAMPLE_COUNT else f"hidden test {index - EXAMPLE_COUNT + 1}"
        if one.get("status") != "success":
            _reject(f"the reference solution failed on {label}: " + str(one.get("stderr") or one.get("output") or "")[-300:])
        found, value, _own = coding_spec.parse_result(str(one.get("stdout") or ""), marker)
        if not found:
            _reject(f"the reference solution returned nothing on {label}")
        try:
            value = coding_spec.check_value(value, spec["returns"], f"{label} (reference)")
        except ValueError as exc:
            _reject(str(exc))
        matches = coding_spec.compare_values(spec, value, case["expected"])
        if index < EXAMPLE_COUNT and not matches:
            _reject(f"the reference solution disagrees with the expected output of {label}: it returned {json.dumps(value)}, the example says {json.dumps(case['expected'])}")
        if matches:
            agreed.append({**case, "expected": value})
    graded_examples, graded_hidden = agreed[:EXAMPLE_COUNT], agreed[EXAMPLE_COUNT:]
    if len(graded_hidden) < HIDDEN_COUNT:
        _reject(f"the reference solution agrees with only {len(graded_hidden)} of the hidden tests; {HIDDEN_COUNT} are required")
    graded_hidden = graded_hidden[:HIDDEN_COUNT]
    if len({json.dumps(c["expected"], sort_keys=True) for c in graded_examples + graded_hidden}) < 2:
        _reject("every test has the same expected output; the tests must tell correct and wrong solutions apart")

    return {
        "id": problem_id, "title": title, "difficulty": difficulty, "description": description, "constraints": constraints,
        "signature": {"name": spec["name"], "params": spec["params"], "returns": spec["returns"]},
        "compare": spec["compare"],
        "examples": [{"explanation": c["explanation"]} for c in graded_examples],
        "starter_code": coding_spec.all_starters(spec),
        "public_test_cases": [{"input": _named(spec, c["values"]), "expected": c["expected"], "explanation": c["explanation"]} for c in graded_examples],
        "hidden_test_cases": [{"input": _named(spec, c["values"]), "expected": c["expected"]} for c in graded_hidden],
        "reference_solution": reference,
    }


